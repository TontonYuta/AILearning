# 6. AGENT CONTEXT WINDOW SUMMARIZER (MEMORY REDUCTION)
# ==============================================================================

class AgentMemoryBuffer:
    """Sliding-window buffer with automatic summarization trigger."""
    def __init__(self, max_messages: int = 4):
        self.max_messages = max_messages
        self.messages: list[str] = []
        self.summary: str = ""

    def add_message(self, message: str):
        self.messages.append(message)
        if len(self.messages) > self.max_messages:
            # Compress the older half into summary
            half = len(self.messages) // 2
            to_compress = self.messages[:half]
            self.summary += " [Summary: " + "; ".join(to_compress) + "]"
            self.messages = self.messages[half:]

    def get_context(self) -> str:
        prefix = f"Archived Context: {self.summary}\n" if self.summary else ""
        return prefix + "\n".join(self.messages)


def test_agent_memory_buffer_compression():
    buffer = AgentMemoryBuffer(max_messages=4)
    for i in range(6):
        buffer.add_message(f"Msg_{i}")

    # Messages buffer should not exceed max_messages
    assert len(buffer.messages) <= 4
    # Summary should contain compressed messages
    assert "Msg_0" in buffer.summary
    assert "Msg_1" in buffer.summary
    # Recent messages remain active
    assert "Msg_5" in buffer.messages


