class SQLSafetyValidator:
    """Validates SQL generated by LLM agents to prevent data destruction."""
    FORBIDDEN_KEYWORDS = {"drop", "delete", "truncate", "alter", "grant", "revoke", "update", "insert"}

    @classmethod
    def is_safe_read_only(cls, sql_query: str) -> tuple[bool, str]:
        cleaned = sql_query.strip().lower()
        # Remove trailing semicolons
        cleaned = cleaned.rstrip(";")
        
        # Must start with select or with (for CTE)
        if not (cleaned.startswith("select") or cleaned.startswith("with")):
            return False, "Query must be a read-only SELECT statement"

        # Check for dangerous keywords as separate tokens
        tokens = cleaned.replace("(", " ").replace(")", " ").split()
        for token in tokens:
            if token in cls.FORBIDDEN_KEYWORDS:
                return False, f"Destructive keyword detected: '{token.upper()}'"

        return True, "SAFE"


def test_sql_safety_validator():
    # Safe queries
    safe_sql_1 = "SELECT id, name, balance FROM customers WHERE balance > 1000;"
    is_safe, msg = SQLSafetyValidator.is_safe_read_only(safe_sql_1)
    assert is_safe
    assert msg == "SAFE"

    safe_sql_2 = "WITH high_val AS (SELECT * FROM orders WHERE total > 500) SELECT * FROM high_val;"
    is_safe, msg = SQLSafetyValidator.is_safe_read_only(safe_sql_2)
    assert is_safe

    # Unsafe queries
    unsafe_sql_1 = "DROP TABLE users;"
    is_safe, msg = SQLSafetyValidator.is_safe_read_only(unsafe_sql_1)
    assert not is_safe
    assert "DROP" in msg or "SELECT" in msg

    unsafe_sql_2 = "SELECT * FROM users; DELETE FROM orders;"
    is_safe, msg = SQLSafetyValidator.is_safe_read_only(unsafe_sql_2)
    assert not is_safe
    assert "DELETE" in msg


