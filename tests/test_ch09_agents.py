class SupervisorRouter:
    """Routes user queries to specialized agents or escalates to human."""
    INTENT_KEYWORDS = {
        "BILLING": ["hóa đơn", "thanh toán", "tiền", "refund", "giá cước", "chi phí"],
        "TECH_SUPPORT": ["lỗi", "sập", "không kết nối", "500", "crash", "bug", "timeout"],
    }

    @classmethod
    def route_query(cls, query: str) -> str:
        q_lower = query.lower()
        # Urgent escalation triggers
        if any(w in q_lower for w in ["gặp giám đốc", "kiện", "lừa đảo", "chuyển con người"]):
            return "HUMAN_ESCALATION"

        for intent, keywords in cls.INTENT_KEYWORDS.items():
            if any(k in q_lower for k in keywords):
                return intent

        return "GENERAL_ASSISTANT"


def test_supervisor_router():
    assert SupervisorRouter.route_query("Tôi muốn hoàn tiền hóa đơn tháng trước") == "BILLING"
    assert SupervisorRouter.route_query("Hệ thống báo lỗi timeout 504") == "TECH_SUPPORT"
    assert SupervisorRouter.route_query("Dịch vụ quá tệ, tôi sẽ kiện công ty bạn") == "HUMAN_ESCALATION"
    assert SupervisorRouter.route_query("Xin chào, hôm nay thời tiết thế nào?") == "GENERAL_ASSISTANT"


